# 读取原始文件并替换category为真实店名
def replace_category_with_real_names(input_file, output_file):
    with open(input_file, 'r', encoding='utf-8') as csvfile:
        reader = csv.DictReader(csvfile)
        fieldnames = reader.fieldnames

        with open(output_file, 'w', encoding='utf-8', newline='') as outfile:
            writer = csv.DictWriter(outfile, fieldnames=fieldnames)
            writer.writeheader()

            # 跟踪每个品类已使用的店名
            used_names = {category: [] for category in category_to_names}

            for row in reader:
                category = row['category']
                if category in category_to_names:
                    # 从该品类的店名列表中随机选择一个未使用的店名
                    available_names = [name for name in category_to_names[category] if name not in used_names[category]]
                    if available_names:
                        new_name = random.choice(available_names)
                        used_names[category].append(new_name)
                    else:
                        # 如果所有店名都已使用，重新开始使用
                        new_name = random.choice(category_to_names[category])
                    row['category'] = new_name
                writer.writerow(row)


